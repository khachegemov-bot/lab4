package ru.lab.cityreports.model;

/**
 * Отдельные права (authorities). Роль — это просто набор прав.
 * В @PreAuthorize проверяем конкретное право, а не название роли:
 * так проще добавить новую роль, не переписывая проверки.
 */
public enum Permission {
    /** подать обращение от своего имени */
    REPORT_CREATE,
    /** подать обращение от имени другого жителя (диспетчер принял жалобу по телефону) */
    REPORT_CREATE_FOR_OTHERS,
    /** видеть все обращения, а не только свои */
    REPORT_READ_ALL,
    /** редактировать любое открытое обращение */
    REPORT_EDIT_ANY,
    /** удалять любое обращение */
    REPORT_DELETE_ANY,
    /** бизнес-операции: назначение, начало, завершение, отмена, передача, отклонение; наряды */
    WORKFLOW_MANAGE,
    /** создавать и изменять городские объекты */
    OBJECT_MANAGE,
    /** удалять городские объекты (каскадно удаляет обращения и наряды) */
    OBJECT_DELETE,
    /** управлять бригадами */
    CREW_MANAGE,
    /** управлять пользователями: список, роли, блокировка, удаление */
    USER_MANAGE
}
